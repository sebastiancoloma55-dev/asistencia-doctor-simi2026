create table if not exists public.historial_colaborador (
  id bigint generated by default as identity primary key,
  colaborador_id uuid references public.colaboradores(id) on delete set null,
  rut text,
  accion text not null check (accion in ('ALTA','ACTUALIZACION','BAJA')),
  antes jsonb,
  despues jsonb,
  actor_email text not null default 'sistema',
  created_at timestamptz not null default now()
);
create index if not exists historial_colaborador_rut_fecha_idx
  on public.historial_colaborador(rut,created_at desc);
alter table public.historial_colaborador enable row level security;
drop policy if exists historial_colaborador_select_permission on public.historial_colaborador;
create policy historial_colaborador_select_permission on public.historial_colaborador
for select to authenticated using (
  public.usuario_es_admin_principal_2026() or public.usuario_tiene_permiso('colaboradores')
);
grant select on public.historial_colaborador to authenticated;
grant all on public.historial_colaborador to service_role;

create or replace function public.registrar_historial_colaborador()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
declare
  before_data jsonb := null;
  after_data jsonb := null;
  row_id uuid;
  row_rut text;
  action_name text;
  actor text := coalesce(nullif(lower((select auth.jwt()->>'email')), ''), 'sistema');
begin
  if tg_op='INSERT' then
    row_id:=new.id; row_rut:=new.rut; action_name:='ALTA';
    after_data:=jsonb_build_object('rut',new.rut,'nombres',new.nombres,'apellidos',new.apellidos,'cargo',new.cargo,'sucursal_id',new.sucursal_id,'sucursal',new.sucursal,'estado',new.estado,'fecha_ingreso',new.fecha_ingreso);
  elsif tg_op='UPDATE' then
    row_id:=new.id; row_rut:=coalesce(new.rut,old.rut); action_name:='ACTUALIZACION';
    before_data:=jsonb_build_object('rut',old.rut,'nombres',old.nombres,'apellidos',old.apellidos,'cargo',old.cargo,'sucursal_id',old.sucursal_id,'sucursal',old.sucursal,'estado',old.estado,'fecha_ingreso',old.fecha_ingreso);
    after_data:=jsonb_build_object('rut',new.rut,'nombres',new.nombres,'apellidos',new.apellidos,'cargo',new.cargo,'sucursal_id',new.sucursal_id,'sucursal',new.sucursal,'estado',new.estado,'fecha_ingreso',new.fecha_ingreso);
    if before_data is not distinct from after_data then return new; end if;
  else
    row_id:=old.id; row_rut:=old.rut; action_name:='BAJA';
    before_data:=jsonb_build_object('rut',old.rut,'nombres',old.nombres,'apellidos',old.apellidos,'cargo',old.cargo,'sucursal_id',old.sucursal_id,'sucursal',old.sucursal,'estado',old.estado,'fecha_ingreso',old.fecha_ingreso);
  end if;
  insert into public.historial_colaborador(colaborador_id,rut,accion,antes,despues,actor_email)
  values(row_id,row_rut,action_name,before_data,after_data,actor);
  if tg_op='DELETE' then return old; end if;
  return new;
end;
$$;
drop trigger if exists colaboradores_historial_automatico on public.colaboradores;
create trigger colaboradores_historial_automatico
after insert or update or delete on public.colaboradores
for each row execute function public.registrar_historial_colaborador();
comment on table public.historial_colaborador is 'Historial de cambios de los campos maestros de colaborador; no incluye datos médicos.';
