-- Create and secure the internal HR meme wall.
-- Applies to the Preview database when the migration is run; no production deployment is performed.
create table if not exists public.memes_rrhh (
  id bigint generated by default as identity primary key,
  titulo text not null check (length(trim(titulo)) > 0),
  descripcion text not null default '',
  imagen_data_url text not null,
  publicado boolean not null default true,
  created_by uuid null references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.memes_rrhh enable row level security;

grant select, insert, delete on public.memes_rrhh to authenticated;
grant usage, select on sequence public.memes_rrhh_id_seq to authenticated;

drop policy if exists "memes_rrhh_read_authenticated" on public.memes_rrhh;
create policy "memes_rrhh_read_authenticated"
on public.memes_rrhh for select to authenticated
using (true);

drop policy if exists "memes_rrhh_insert_authenticated" on public.memes_rrhh;
create policy "memes_rrhh_insert_authenticated"
on public.memes_rrhh for insert to authenticated
with check (
  created_by is null
  or created_by = auth.uid()
  or coalesce(public.usuario_es_admin_principal_2026(), false)
);

drop policy if exists "memes_rrhh_delete_admin_or_author" on public.memes_rrhh;
create policy "memes_rrhh_delete_admin_or_author"
on public.memes_rrhh for delete to authenticated
using (
  coalesce(public.usuario_es_admin_principal_2026(), false)
  or created_by = auth.uid()
  or exists (
    select 1
    from public.usuarios_roles ur
    where lower(ur.email) = lower(coalesce(auth.jwt()->>'email',''))
      and ur.activo is distinct from false
      and ur.acceso_global is true
  )
);

create index if not exists memes_rrhh_publicado_created_at_idx
on public.memes_rrhh (publicado, created_at desc);
