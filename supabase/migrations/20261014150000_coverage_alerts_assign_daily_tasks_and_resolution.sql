-- Cobertura workflow: explicitly assigned users, daily-task inbox and resolution gate.
alter table public.tareas
  add column if not exists solicitud_dotacion_id uuid
  references public.solicitudes_dotacion(id) on delete set null;

alter table public.coberturas
  add column if not exists solicitud_dotacion_id uuid
  references public.solicitudes_dotacion(id) on delete set null;
create index if not exists idx_coberturas_solicitud_dotacion
  on public.coberturas(solicitud_dotacion_id)
  where solicitud_dotacion_id is not null;

create index if not exists idx_tareas_solicitud_dotacion
  on public.tareas(solicitud_dotacion_id)
  where solicitud_dotacion_id is not null;

create table if not exists public.solicitud_dotacion_responsables (
  id bigint generated by default as identity primary key,
  solicitud_id uuid not null references public.solicitudes_dotacion(id) on delete cascade,
  usuario_rol_id bigint not null references public.usuarios_roles(id) on delete restrict,
  tarea_id bigint references public.tareas(id) on delete set null,
  asignado_por bigint not null references public.usuarios_roles(id) on delete restrict,
  created_at timestamptz not null default now(),
  unique (solicitud_id, usuario_rol_id)
);
create index if not exists idx_solicitud_dotacion_responsables_usuario
  on public.solicitud_dotacion_responsables(usuario_rol_id, solicitud_id);

alter table public.solicitud_dotacion_responsables enable row level security;
drop policy if exists solicitud_dotacion_responsables_select on public.solicitud_dotacion_responsables;
create policy solicitud_dotacion_responsables_select
on public.solicitud_dotacion_responsables for select to authenticated
using (
  usuario_rol_id = public.chat_usuario_actual_id()
  or asignado_por = public.chat_usuario_actual_id()
  or public.usuario_es_admin_principal_2026()
  or public.usuario_tiene_alguno_permiso(array['traslados','coberturas','amonestaciones']::text[])
);
grant select on public.solicitud_dotacion_responsables to authenticated;

create or replace function public.crear_alerta_cobertura_asignada(
  p_sucursal_id uuid,
  p_sucursal_nombre text,
  p_fecha_inicio date,
  p_fecha_fin date,
  p_cantidad integer,
  p_cargo_requerido text,
  p_turno text,
  p_hora_inicio time,
  p_hora_fin time,
  p_motivo text,
  p_observaciones text,
  p_destinatarios bigint[]
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_solicitud_id uuid;
  v_solicitante bigint;
  v_email text;
  v_usuario bigint;
  v_tarea_id bigint;
  v_mensaje text;
begin
  v_solicitante := public.chat_usuario_actual_id();
  if v_solicitante is null then
    raise exception 'Tu usuario no tiene un perfil activo.';
  end if;
  if not (public.usuario_es_admin_principal_2026()
      or public.usuario_tiene_alguno_permiso(array['traslados','coberturas','amonestaciones']::text[])) then
    raise exception 'No tienes permiso para crear alertas de cobertura.';
  end if;
  if coalesce(array_length(p_destinatarios, 1), 0) < 1 then
    raise exception 'Selecciona al menos una persona responsable.';
  end if;
  if p_fecha_fin < p_fecha_inicio then
    raise exception 'La fecha de término no puede ser anterior al inicio.';
  end if;
  if p_cantidad < 1 or p_cantidad > 100 then
    raise exception 'La cantidad debe estar entre 1 y 100.';
  end if;
  if exists (
    select 1 from unnest(p_destinatarios) recipient_id
    left join public.usuarios_roles u on u.id = recipient_id
    where u.id is null or not coalesce(u.activo, false)
  ) then
    raise exception 'Uno o más responsables no existen o están inactivos. Actualiza la lista e inténtalo de nuevo.';
  end if;

  insert into public.solicitudes_dotacion (
    sucursal_id, sucursal_nombre, fecha_inicio, fecha_fin, cantidad,
    cargo_requerido, turno, hora_inicio, hora_fin, motivo, observaciones,
    estado, solicitada_por
  ) values (
    p_sucursal_id, trim(p_sucursal_nombre), p_fecha_inicio, p_fecha_fin, p_cantidad,
    p_cargo_requerido, p_turno, p_hora_inicio, p_hora_fin, trim(p_motivo),
    nullif(trim(coalesce(p_observaciones, '')), ''),
    'PENDIENTE', v_solicitante
  ) returning id into v_solicitud_id;

  select email into v_email from public.usuarios_roles where id = v_solicitante;
  v_mensaje := 'Sucursal: ' || trim(p_sucursal_nombre)
    || '. Cargo: ' || p_cargo_requerido || '. Turno: ' || p_turno
    || '. Período: ' || p_fecha_inicio::text || ' a ' || p_fecha_fin::text
    || '. Cantidad: ' || p_cantidad::text || '. Motivo: ' || trim(p_motivo)
    || '. Alerta: ' || v_solicitud_id::text
    || '. Gestiona esta tarea desde Tareas diarias.';

  for v_usuario in
    select distinct recipient_id from unnest(p_destinatarios) recipient_id
  loop
    insert into public.solicitud_dotacion_responsables(solicitud_id, usuario_rol_id, asignado_por)
    values (v_solicitud_id, v_usuario, v_solicitante);

    insert into public.tareas (
      titulo, descripcion, responsable_rol_id, revisor_rol_id, sucursal_id,
      prioridad, estado, recurrencia, fecha_limite, clave_evento,
      creado_por_email, solicitud_dotacion_id
    ) values (
      'Gestionar cobertura · ' || trim(p_sucursal_nombre),
      v_mensaje, v_usuario, v_solicitante, p_sucursal_id,
      'ALTA', 'PENDIENTE', 'NINGUNA',
      ((p_fecha_inicio + time '23:59:00') at time zone 'America/Santiago'),
      'COBERTURA:' || v_solicitud_id::text || ':' || v_usuario::text,
      coalesce(v_email, 'sistema@asistencia-doctor-simi.local'), v_solicitud_id
    ) returning id into v_tarea_id;

    update public.solicitud_dotacion_responsables
      set tarea_id = v_tarea_id
      where solicitud_id = v_solicitud_id and usuario_rol_id = v_usuario;

    insert into public.notificaciones(
      usuario_rol_id, tipo, titulo, mensaje, entidad_tipo, leida
    ) values (
      v_usuario, 'COBERTURA_ASIGNADA', 'Nueva tarea diaria: cobertura',
      v_mensaje, 'solicitud_dotacion', false
    );

    insert into public.tareas_eventos(
      tarea_id, accion, estado_nuevo, usuario_email, detalle
    ) values (
      v_tarea_id, 'CREADA_POR_COBERTURA', 'PENDIENTE',
      coalesce(v_email, 'sistema@asistencia-doctor-simi.local'),
      'Tarea creada desde la alerta de cobertura ' || v_solicitud_id::text
    );
  end loop;

  return v_solicitud_id;
end;
$$;

revoke all on function public.crear_alerta_cobertura_asignada(uuid,text,date,date,integer,text,text,time,time,text,text,bigint[]) from public, anon;
grant execute on function public.crear_alerta_cobertura_asignada(uuid,text,date,date,integer,text,text,time,time,text,text,bigint[]) to authenticated;

