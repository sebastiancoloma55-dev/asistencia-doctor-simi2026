-- Notifications for new alerts are sent only to explicitly assigned recipients by the RPC above.
-- Keep status-change notifications to the requester without broadcasting alert creation to all staff.
create or replace function public.notificar_cambios_solicitud_dotacion()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_titulo text;
  v_mensaje text;
begin
  if tg_op = 'INSERT' then
    return new;
  end if;
  if tg_op = 'UPDATE' and new.estado is distinct from old.estado then
    v_titulo := case
      when new.estado = 'APROBADA' then 'Necesidad de cobertura aprobada'
      when new.estado = 'RECHAZADA' then 'Necesidad de cobertura rechazada'
      when new.estado = 'CUBIERTA' then 'Cobertura marcada como resuelta'
      else 'Actualización de necesidad de cobertura'
    end;
    v_mensaje := 'Tu solicitud para ' || new.sucursal_nombre || ' (' || new.fecha_inicio::text || ' a ' || new.fecha_fin::text || ') cambió a estado: ' || new.estado || '.';
    insert into public.notificaciones(usuario_rol_id,tipo,titulo,mensaje,entidad_tipo,leida)
    values(new.solicitada_por,'COBERTURA_DOTACION',v_titulo,v_mensaje,'solicitud_dotacion',false);
  end if;
  return new;
end;
$$;

-- Safe directory for the responsible-user picker without granting broad user-directory reads.
create or replace function public.listar_responsables_cobertura()
returns table(id bigint, nombre text, email text)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not (public.usuario_es_admin_principal_2026()
      or public.usuario_tiene_alguno_permiso(array['traslados','coberturas','amonestaciones']::text[])) then
    raise exception 'No tienes permiso para asignar alertas de cobertura.';
  end if;
  return query
    select u.id, u.nombre, u.email
    from public.usuarios_roles u
    where coalesce(u.activo, false)
    order by coalesce(u.nombre, u.email), u.email
    limit 500;
end;
$$;
revoke all on function public.listar_responsables_cobertura() from public, anon;
grant execute on function public.listar_responsables_cobertura() to authenticated;

