-- Tabla para guardar acuerdos de compensación desde Asistencia Doctor Simi.
-- Aplicar manualmente en Supabase después de revisar las políticas RLS.
create table if not exists public.acuerdos_compensacion (
  id bigint generated by default as identity primary key,
  colaborador_id text,
  nombre text not null,
  rut text not null,
  cargo text,
  fecha_ingreso date,
  fecha_acuerdo date not null,
  fecha_trabajada_desde date not null,
  fecha_trabajada_hasta date not null,
  dias_compensar integer not null check (dias_compensar > 0),
  fecha_descanso_acordada date not null,
  notas_internas text,
  generado_por text,
  created_at timestamptz not null default now(),
  constraint acuerdos_compensacion_fechas_check check (fecha_trabajada_hasta >= fecha_trabajada_desde)
);
alter table public.acuerdos_compensacion enable row level security;
