-- Tabla para acuerdos de compensación de Asistencia Doctor Simi.
create table if not exists public.acuerdos_compensacion (
  id bigint generated by default as identity primary key,
  colaborador_id text,
  nombre text not null,
  rut text not null,
  cargo text,
  fecha_ingreso date,
  fecha_acuerdo date not null,
  fecha_trabajada_desde date not null,
  fecha_trabajada_hasta date not null,
  dias_compensar integer not null check (dias_compensar > 0),
  fecha_descanso_acordada date not null,
  notas_internas text,
  generado_por text,
  created_at timestamptz not null default now(),
  constraint acuerdos_compensacion_fechas_check check (fecha_trabajada_hasta >= fecha_trabajada_desde)
);
alter table public.acuerdos_compensacion enable row level security;

drop policy if exists "RRHH puede leer acuerdos autorizados" on public.acuerdos_compensacion;
create policy "RRHH puede leer acuerdos autorizados"
on public.acuerdos_compensacion for select to authenticated
using (
  lower(coalesce(auth.jwt()->>'email','')) = 'scoloma@farmaciasdoctorsimi.cl'
  or exists (
    select 1 from public.usuarios_roles ur
    where lower(ur.email) = lower(coalesce(auth.jwt()->>'email',''))
      and ur.activo is distinct from false
      and (ur.acceso_global is true or ur.permisos @> '["acuerdos-compensacion"]'::jsonb)
  )
);

drop policy if exists "RRHH autorizado puede crear acuerdos" on public.acuerdos_compensacion;
create policy "RRHH autorizado puede crear acuerdos"
on public.acuerdos_compensacion for insert to authenticated
with check (
  lower(coalesce(auth.jwt()->>'email','')) = 'scoloma@farmaciasdoctorsimi.cl'
  or exists (
    select 1 from public.usuarios_roles ur
    where lower(ur.email) = lower(coalesce(auth.jwt()->>'email',''))
      and ur.activo is distinct from false
      and (ur.acceso_global is true or ur.permisos @> '["acuerdos-compensacion"]'::jsonb)
  )
);
